SEED_TEMPLATES = REQUESTED_SCRIPT_TEMPLATES


def seed_templates():
    """导入种子模板和爆款脚本"""
    db = SessionLocal()
    try:
        # 导入脚本模板
        existing_tpl = db.query(ScriptTemplate).count()
        if existing_tpl > 0:
            print(f"  已有 {existing_tpl} 个脚本模板，跳过导入")
        else:
            for tpl in REQUESTED_SCRIPT_TEMPLATES:
                db.add(ScriptTemplate(**tpl))
            db.commit()
            print(f"  ✅ 已导入 {len(REQUESTED_SCRIPT_TEMPLATES)} 个脚本模板")

        # 导入爆款脚本参考
        existing_viral = db.query(ViralScript).count()
        if existing_viral > 0:
            print(f"  已有 {existing_viral} 条爆款脚本，跳过导入")
        else:
            for vs in SEED_VIRAL_SCRIPTS:
                script_data = dict(vs)
                script_data["video_type"] = map_script_type(script_data.get("video_type"))
                db.add(ViralScript(**script_data))
            db.commit()
            print(f"  ✅ 已导入 {len(SEED_VIRAL_SCRIPTS)} 条爆款脚本参考")
    except Exception as e:
        db.rollback()
        print(f"  ❌ 模板数据导入失败: {e}")
    finally:
        db.close()


